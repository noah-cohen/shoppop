import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';

export function openDatabase(directory) {
  mkdirSync(directory, { recursive: true });
  const db = new DatabaseSync(join(directory, 'calendar.sqlite'));
  db.exec(`PRAGMA foreign_keys = ON; PRAGMA journal_mode = WAL; ${databaseSchema('sqlite')}`);
  return db;
}

export function databaseSchema(dialect) {
  const id = dialect === 'postgres' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const timestamp = dialect === 'postgres' ? 'DOUBLE PRECISION' : 'INTEGER';
  const bytes = dialect === 'postgres' ? 'BYTEA' : 'BLOB';
  return `
    CREATE TABLE IF NOT EXISTS stores (id ${id}, data TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS venues (id ${id}, data TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS sales (
      id ${id}, venue_id INTEGER NOT NULL REFERENCES venues(id),
      data TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS sale_stores (
      sale_id INTEGER NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
      store_id INTEGER NOT NULL REFERENCES stores(id),
      PRIMARY KEY (sale_id, store_id)
    );
    CREATE TABLE IF NOT EXISTS admin (id INTEGER PRIMARY KEY CHECK(id=1), hash TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, expires ${timestamp} NOT NULL);
    CREATE TABLE IF NOT EXISTS media (
      id TEXT PRIMARY KEY, mime TEXT NOT NULL, bytes ${bytes} NOT NULL, created ${timestamp} NOT NULL
    );
    CREATE TABLE IF NOT EXISTS submissions (
      id ${id}, data TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
      created ${timestamp} NOT NULL, reviewed ${timestamp}, sale_id INTEGER REFERENCES sales(id) ON DELETE SET NULL,
      poster_id TEXT REFERENCES media(id) ON DELETE SET NULL
    );
    CREATE TABLE IF NOT EXISTS messages (
      id ${id}, data TEXT NOT NULL, created ${timestamp} NOT NULL,
      is_read INTEGER NOT NULL DEFAULT 0 CHECK(is_read IN (0,1))
    );
    CREATE TABLE IF NOT EXISTS users (
      id ${id}, email TEXT NOT NULL UNIQUE, created ${timestamp} NOT NULL,
      last_login ${timestamp} NOT NULL
    );
    CREATE TABLE IF NOT EXISTS login_codes (
      email TEXT PRIMARY KEY, hash TEXT NOT NULL, expires ${timestamp} NOT NULL,
      attempts INTEGER NOT NULL DEFAULT 0, requested ${timestamp} NOT NULL
    );
    CREATE TABLE IF NOT EXISTS user_sessions (
      token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires ${timestamp} NOT NULL
    );
    CREATE TABLE IF NOT EXISTS user_favorites (
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      type TEXT NOT NULL CHECK(type IN ('sales','stores')),
      entity_id INTEGER NOT NULL CHECK(entity_id > 0),
      PRIMARY KEY (user_id, type, entity_id)
    );
    CREATE TABLE IF NOT EXISTS user_credentials (
      user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      password_hash TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS user_profiles (
      user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      data TEXT NOT NULL, updated ${timestamp} NOT NULL
    );
    CREATE TABLE IF NOT EXISTS auth_codes (
      email TEXT NOT NULL, purpose TEXT NOT NULL CHECK(purpose IN ('register','login','reset')),
      hash TEXT NOT NULL, expires ${timestamp} NOT NULL, attempts INTEGER NOT NULL DEFAULT 0,
      requested ${timestamp} NOT NULL, PRIMARY KEY (email, purpose)
    );
    CREATE TABLE IF NOT EXISTS pending_registrations (
      email TEXT PRIMARY KEY, password_hash TEXT NOT NULL, profile TEXT NOT NULL,
      expires ${timestamp} NOT NULL
    );
  `;
}

export async function mediaIsPublished(db, id) {
  const query = db.dialect === 'postgres'
    ? `SELECT 1 FROM sales, jsonb_array_elements(sales.data::jsonb->'stores') AS participant WHERE participant->>'posterId'=? LIMIT 1`
    : `SELECT 1 FROM sales, json_each(sales.data, '$.stores') AS participant WHERE json_extract(participant.value, '$.posterId')=? LIMIT 1`;
  return Boolean(await db.prepare(query).get(id));
}

export async function pruneUnusedMedia(db) {
  const references = db.dialect === 'postgres'
    ? `SELECT participant->>'posterId' FROM sales, jsonb_array_elements(sales.data::jsonb->'stores') AS participant WHERE participant->>'posterId' IS NOT NULL`
    : `SELECT json_extract(participant.value, '$.posterId') FROM sales, json_each(sales.data, '$.stores') AS participant WHERE json_extract(participant.value, '$.posterId') IS NOT NULL`;
  await db.prepare(`DELETE FROM media WHERE created < ? AND id NOT IN (
    ${references}
  ) AND id NOT IN (SELECT poster_id FROM submissions WHERE poster_id IS NOT NULL AND status='pending')`).run(Date.now() - 86400_000);
}

export async function readAll(db) {
  return Object.fromEntries(await Promise.all(['stores', 'venues', 'sales'].map(async table => [
    table, (await db.prepare(`SELECT id, data FROM ${table} ORDER BY id DESC`).all())
      .map(row => ({ ...JSON.parse(row.data), id: row.id })),
  ])));
}

export async function saveSale(db, data, id) {
  if (id === undefined) id = (await db.prepare('INSERT INTO sales (venue_id,data) VALUES (?,?) RETURNING id').get(data.venueId, JSON.stringify(data))).id;
  else await db.prepare('UPDATE sales SET venue_id=?, data=? WHERE id=?').run(data.venueId, JSON.stringify(data), id);
  await db.prepare('DELETE FROM sale_stores WHERE sale_id=?').run(id);
  for (const store of data.stores) await db.prepare('INSERT INTO sale_stores VALUES (?,?)').run(id, store.storeId);
  return id;
}
